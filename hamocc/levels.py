_ALIASES = {"pp_tot": "ppint"}


def fixed_levels(kind, name, plots_cfg=None):
    """(levels, difference levels) for variable `name`, or (None, None) when there are none.

    `kind` is 'map' (2-D fields and depth slices) or 'zonal'. The recipe's `plots.levels.<kind>.<name>`
    (keys `levels`, `diff_levels`) replaces the legacy table; the legacy table is used only when
    `plots.fixed_levels` is true. Either level list may be None (quantile levels are used then).
    """
    plots_cfg = plots_cfg or {}
    custom = (plots_cfg.get("levels") or {}).get(kind, {}).get(name)
    if custom:
        return custom.get("levels"), custom.get("diff_levels")
    if not plots_cfg.get("fixed_levels"):
        return None, None
    name = _ALIASES.get(name, name)
    table = ZONAL_LEVELS if kind == "zonal" else {**SURFACE_LEVELS, **DEPTH_MAP_LEVELS}
    levels, diff = table.get(name, (None, None))
    return levels, diff
